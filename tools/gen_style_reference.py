"""Regenerates docs/STYLE_REFERENCE.md from the code (keys, descriptions and
the values of every built-in style), so the reference can never drift.

    PYTHONPATH=build/python QT_QPA_PLATFORM=offscreen python3 tools/gen_style_reference.py
"""
import os
import sys

import plotter.style as style

HEADER = """# Style reference

Every visual setting is a style key. Use them in `.gpstyle` files (`key: value`),
in *Style → Edit style…*, or from Python (`plotter.style.set({...})`,
`fig.set_style({...})`). This file is generated by `tools/gen_style_reference.py`.

## Style files

```text
# thesis.gpstyle — comments start with '#'
inherit: science                 # start from a built-in style or another file
font.size: 11
axes.prop_cycle: #1b9e77, #d95f02, #7570b3
label.top.left: "**My Experiment** *Preliminary*"
label.inside: "#1 candidate"     # quote values that contain '#'
```

Rules:

- One `key: value` per line; empty lines are ignored.
- **Comments:** `#` starts a comment, except where a colour begins (directly
  after `:` or `,`, as in `#1b9e77`). Put values that contain `#` in double
  quotes. Inside quotes, write `""` for a literal `"`.
- **inherit:** a built-in name or a file; a relative path is relative to the
  file that contains it. Usually the first line; keys set *before* it are
  applied again on top of the inherited style. Chains may be up to 8 deep.
- **Booleans:** `true`/`false`, `yes`/`no`, `on`/`off`, `1`/`0`.
- **Numbers:** finite, at most 10⁶ in magnitude; sizes and widths ≥ 0;
  `xtick.count` / `ytick.count` 1–50; `contour.levels` 1–200;
  `contour.factor` > 1.
- **Colours:** `#rrggbb`, `#aarrggbb` (**alpha first**, e.g. `#80ff0000` is
  half-transparent red), SVG names (`navy`), or the palette names (`red`,
  `blue`, `green`, … map to the palette tones; see the Python reference).
  Lists (`axes.prop_cycle`) are comma-separated.
- **Errors:** unknown keys and invalid values are reported with their line
  number and skipped; the rest of the file still applies.
- **Your default style:** `~/.config/Graphplot/default.gpstyle`, or the file
  named by `$GRAPHPLOT_STYLE`, is loaded at start-up (*Style → Use as my
  default style* writes it).

## Built-in styles

| Name | Purpose |
|---|---|
| `default` | clean screen style with a light grid |
| `science` | publication / HEP style: closed frame, inward ticks on all sides, minor ticks, no grid |
| `nmr` | TopSpin-like spectrum display: no grid, outward ticks, thin contours, 16 levels with factor 1.3 |
| `presentation` | larger fonts and thicker lines for slides |

## All keys

"""


def main():
    names = style.available()
    keys = style.keys()
    values = {}
    for n in names:
        style.use(n)
        values[n] = {k: style.get(k) for k in keys}
    style.use("default")

    def cell(v):
        v = v.replace("|", "\\\\|")
        return f"`{v}`" if v else "(empty)"

    lines = [HEADER.rstrip("\n"), "",
             "| Key | " + " | ".join(names) + " | Description |",
             "|---|" + "---|" * len(names) + "---|"]
    for k, desc in keys.items():
        lines.append(f"| `{k}` | " + " | ".join(cell(values[n][k]) for n in names) + f" | {desc} |")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "STYLE_REFERENCE.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(keys)} keys x {len(names)} styles to {os.path.normpath(out)}", file=sys.stderr)


if __name__ == "__main__":
    main()
